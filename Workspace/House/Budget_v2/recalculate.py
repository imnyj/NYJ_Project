# 지출 항목 파싱
parsed_items = []
mother_allowance = 0
for line in raw_lines:
    parts = line.split("\t")
    if len(parts) < 3:
        continue
    date = parts[0].strip()
    desc = parts[1].strip()
    amt = int(parts[2].strip())
    if "엄마가 이 날 쓰라고 돈 줌" in desc:
        mother_allowance = abs(amt)
    else:
        parsed_items.append((date, desc, amt))

# 8월 16일 상계 처리
# 8월 16일에 해당하는 친구들과 논 금액: 친구들 PC방비, 친구들 식사비, 친구들 커피, 군것질(1500원짜리)
aug_16_play_amt = 0
aug_16_play_items = []
other_items = []

for date, desc, amt in parsed_items:
    if date == "08월 16일" and any(k in desc for k in ["친구들", "군것질"]):
        aug_16_play_amt += amt
        aug_16_play_items.append((desc, amt))
    else:
        other_items.append((date, desc, amt))

# 20만원 한도 상계
remaining_allowance = mother_allowance - aug_16_play_amt # 200,000 - 140,900 = 59,100원

# 상계 후 결과
# 친구들과 논 비용은 0원으로 지출에서 제외됨
# 남은 잔액 59,100원은 통장 잔고 이득(수입/지출 차감)으로 반영
final_items = []
for date, desc, amt in other_items:
    # 8월 18일 폰 요금제는 41628원으로 대체
    if date == "08월 18일" and "폰 요금제" in desc:
        final_items.append((date, "폰 요금제 (추후 요금 적용)", 41628))
    else:
        final_items.append((date, desc, amt))

# 카테고리 재분류 함수
# v1과 직접 비교가 가능하도록 v1의 분류 체계를 최대한 따름
def categorize_v1(desc):
    d = desc.strip()
    
    # 1. 주거비/공과금
    if any(k in d for k in ["월세", "전기세", "가스비", "수도세", "주민세"]):
        return "주거비/공과금"
    # 2. 통신비
    if "폰 요금제" in d:
        return "통신비"
    # 3. 보험료
    if "보험" in d:
        return "보험료"
    # 4. 구독료
    if any(k in d for k in ["유튜브", "넷플릭스", "구글", "AI1", "AI2", "알림서비스"]):
        return "구독료"
    # 5. 저축/투자
    if any(k in d for k in ["엔비디아", "청약"]):
        return "저축/투자"
    
    # 변동지출
    # 6. 식비 (외식/배달)
    # v1과 일치시키기 위해: 가족 식사와 은비와의 외식을 식비로 분류할 경우를 비교하기 위함
    # v1에서는 은비와 외식, 부모님과 식사가 모두 "식비"에 들어갔음.
    # 단, 이번에는 사용자가 "데이트 비용이 줄었고, 가족 식사 비용도 줄었는데 왜 큰 것 같지?"라고 지적했으므로
    # v1 분류 방식을 적용하여 "은비"가 들어간 식음료는 [데이트]가 아닌 [식비]로,
    # "가족/부모님"이 들어간 식음료도 [가족]이 아닌 [식비]로 분류해서 계산해본다.
    # 즉, v1의 원래 식비 정의: "은비와 외식", "부모님과 식사", "군산 외식", "커피 쏘기" 등
    
    # 7. 교통비 (주유/톨게이트/택시/기차)
    if any(k in d for k in ["주유", "기름", "하이패스", "택시", "기차"]):
        return "교통비"
    # 8. 차량 관리 (세차/주차)
    if any(k in d for k in ["세차", "주차"]):
        return "차량 관리"
    # 9. 쇼핑/생필품
    if any(k in d for k in ["생필품", "옷", "쿠팡 취미", "미용실", "바디프렌드"]):
        return "쇼핑/생필품"
    # 10. 문화/여가/게임
    if any(k in d for k in ["노래방", "PC방", "피씨방", "영화", "롯데월드"]):
        # 롯데월드 입장권/도넛/보조배터리 등은 문화 여가
        return "문화/여가/게임"
    # 11. 데이트/모임비 (v1 기준: 모텔비, 모임비만 해당)
    if any(k in d for k in ["숙박", "모텔", "모임비", "계곡 추가 숙소"]):
        return "데이트/모임비"
    # 12. 경조사/선물/기부
    if any(k in d for k in ["부조", "기부", "화환"]):
        return "경조사/선물/기부"
    
    # 기본 분류
    # 은비 식사/야식/카페는 식비로 우선 분류
    if any(k in d for k in ["식사", "야식", "편의점", "카페", "커피", "도넛", "장보기", "외식", "군것질"]):
        return "식비/카페"
        
    return "기타"

# v1 기준 분류 시뮬레이션
v1_categories = defaultdict(lambda: {"total": 0, "items": []})
total_expense_v1 = 0

# 엄격한 v2 분류 (데이트와 가족을 독립적으로 둔 것)
v2_categories = defaultdict(lambda: {"total": 0, "items": []})
total_expense_v2 = 0

for date, desc, amt in final_items:
    # 농협카드비, 모름 제외 (v1에선 모름이 기타 변동비에 들어가거나 카드비는 이중지출 우려 있음)
    if "카드비" in desc or "카드대금" in desc or "농협카드비" in desc:
        continue
    
    # v1 스타일 분류
    cat_v1 = categorize_v1(desc)
    # 은비와 식사/야식을 v1 스타일로 다시 쪼개서 분류
    if "은비와" in desc or "은비 편의점" in desc:
        if any(k in desc for k in ["야식", "편의점", "카페", "커피", "점심", "도넛"]):
            cat_v1 = "식비/카페 (데이트 식비 포함)"
        elif any(k in desc for k in ["숙박", "모텔"]):
            cat_v1 = "데이트/모임비 (숙박/모임만)"
        else:
            cat_v1 = "데이트/모임비 (기타)"
    elif "가족" in desc or "부모님" in desc:
        if any(k in desc for k in ["식사", "카페", "커피"]):
            cat_v1 = "식비/카페 (가족 식비 포함)"
    
    v1_categories[cat_v1]["total"] += amt
    v1_categories[cat_v1]["items"].append((date, desc, amt))
    total_expense_v1 += amt

print("=" * 70)
print("상계 처리 및 통신비 수정 후 결과")
print(f"상계 후 남은 용돈 잔액: {remaining_allowance:,}원 (통고 잔액 플러스)")
print(f"순수 지출 총액 (카드비/상계항목 제외): {total_expense_v1:,}원")
print("=" * 70)

for cat, data in sorted(v1_categories.items(), key=lambda x: x[1]["total"], reverse=True):
    pct = data["total"] / total_expense_v1 * 100
    print(f"\n* {cat}: {data['total']:,}원 ({pct:.1f}%)")
    # 상위 5개만 출력
    for date, desc, amt in data["items"][:5]:
        print(f"  - {date} {desc} ({amt:,}원)")
    if len(data["items"]) > 5:
        print(f"  - 외 {len(data['items'])-5}건")
