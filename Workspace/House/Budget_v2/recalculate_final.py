# 지출 통계 계산
categories = defaultdict(lambda: {"total": 0, "items": []})
total_spent = 0

def get_cat(desc):
    d = desc.strip()
    if any(k in d for k in ["은비", "모텔", "롯데월드"]):
        return "데이트"
    if any(k in d for k in ["주유", "기름", "하이패스", "택시", "기차", "주차"]):
        return "교통"
    if any(k in d for k in ["엔비디아", "청약"]):
        return "저축/투자"
    if any(k in d for k in ["월세", "전기", "가스", "수도", "주민세"]):
        return "월세/공과금"
    if any(k in d for k in ["보험", "현대해상", "삼성생명", "DB"]):
        return "보험"
    if any(k in d for k in ["부조", "기부", "화환"]):
        return "경조사"
    if any(k in d for k in ["모임"]):
        return "모임"
    if any(k in d for k in ["쏘기", "학생 논문"]):
        return "쏘기"
    if any(k in d for k in ["가족"]):
        return "가족"
    if any(k in d for k in ["유튜브", "넷플릭스", "구글", "AI1", "AI2", "알림"]):
        return "구독/서비스"
    if any(k in d for k in ["폰 요금", "통신"]):
        return "통신"
    if any(k in d for k in ["친구", "PC방", "피씨방"]):
        return "친구/놀이"
    if any(k in d for k in ["옷", "쿠팡 취미", "미용", "바디프렌드", "세차"]):
        return "취미/쇼핑"
    if any(k in d for k in ["외식", "식사", "장보기", "편의점", "커피", "카페", "군것질", "야식", "생필품", "계곡"]):
        return "식비/혼밥"
    if any(k in d for k in ["벌금"]):
        return "벌금/과태료"
    if any(k in d for k in ["노래방"]):
        return "놀이"
    if "모름" in d:
        return "미분류"
    return "기타"

for date, desc, amt in recalculated_expenses:
    cat = get_cat(desc)
    categories[cat]["total"] += amt
    categories[cat]["items"].append((date, desc, amt))
    total_spent += amt

print(f"단순 지출 총합: {total_spent:,}원")
# 통장 잔고 이득(59,100원)을 차감하여 순 지출 도출
net_spent = total_spent - net_aug_16_diff
print(f"최종 순 지출: {net_spent:,}원")

# 카테고리 출력
sorted_cats = sorted(categories.items(), key=lambda x: x[1]["total"], reverse=True)
for cat, data in sorted_cats:
    pct = data["total"] / total_spent * 100
    print(f"\n{cat}: {data['total']:,}원 ({pct:.1f}%)")
