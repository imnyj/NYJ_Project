def replace_math_notations(text):
    out = []
    pos = 0
    while pos < len(text):
        if text.startswith('$$', pos):
            end = text.find('$$', pos + 2)
            if end != -1:
                block = text[pos+2:end]
                block_rep = re.sub(r'(?<!\\text\{)CBR', lambda m: r'\text{CBR}', block)
                block_rep = re.sub(r'T_{\\text\{gen\}}', lambda m: r'T_{\\text{GenCam}}', block_rep)
                block_rep = re.sub(r'T_{\\text\{GenCAM\}}', lambda m: r'T_{\\text{GenCam}}', block_rep)
                out.append('$$' + block_rep + '$$')
                pos = end + 2
                continue
        if text.startswith('$', pos):
            end = text.find('$', pos + 1)
            if end != -1:
                block = text[pos+1:end]
                block_rep = re.sub(r'(?<!\\text\{)CBR', lambda m: r'\text{CBR}', block)
                block_rep = re.sub(r'T_{\\text\{gen\}}', lambda m: r'T_{\\text{GenCam}}', block_rep)
                block_rep = re.sub(r'T_{\\text\{GenCAM\}}', lambda m: r'T_{\\text{GenCam}}', block_rep)
                out.append('$' + block_rep + '$')
                pos = end + 1
                continue
        out.append(text[pos])
        pos += 1
    return ''.join(out)

